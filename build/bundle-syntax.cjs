const fs = require('node:fs'),
  path = require('node:path');
const root = path.join(__dirname, '..'),
  library = path.dirname(require.resolve('prismjs/package.json'));
const languages = [
  'markup',
  'css',
  'clike',
  'javascript',
  'typescript',
  'jsx',
  'tsx',
  'python',
  'json',
  'bash',
  'powershell',
  'yaml',
  'markdown',
  'rust',
  'go',
  'java',
  'csharp',
  'c',
  'cpp',
  'sql',
  'ruby',
];
const license = fs.readFileSync(path.join(library, 'LICENSE'), 'utf8'),
  version = require('prismjs/package.json').version;
const output =
  '/* Prism ' +
  version +
  '; generated by build/bundle-syntax.cjs.\n' +
  license +
  '\n*/\nself.Prism={manual:true,disableWorkerMessageHandler:true};\n' +
  ['core', ...languages]
    .map((name) => fs.readFileSync(path.join(library, 'components', 'prism-' + name + '.min.js'), 'utf8'))
    .join('\n');
const destination = path.join(root, 'syntax-highlight.js');
if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output)
  fs.writeFileSync(destination, output);
console.log('Bundled syntax grammars for ' + languages.length + ' languages.');
